create table if not exists public.bank_disciplines (
    id bigint generated by default as identity primary key,
    code text not null unique,
    name text not null unique
);

create table if not exists public.bank_domains (
    id bigint generated by default as identity primary key,
    discipline_id bigint not null references public.bank_disciplines(id),
    name text not null,
    position integer not null,
    unique (discipline_id, name)
);

create table if not exists public.bank_questions (
    id bigint generated by default as identity primary key,
    discipline_id bigint not null references public.bank_disciplines(id),
    domain_id bigint not null references public.bank_domains(id),
    source_file text not null,
    source_no integer not null,
    cognitive_level text not null
        check (cognitive_level in ('Remember', 'Understand', 'Apply', 'Analyze')),
    difficulty text not null check (difficulty in ('Easy', 'Medium', 'Hard')),
    question_type text not null
        check (question_type in ('multiple_choice', 'identification', 'both')),
    question_text text not null,
    image_path text,
    answer_letter text check (answer_letter in ('A', 'B', 'C', 'D', 'E')),
    answer_text text not null,
    unique (discipline_id, source_no)
);
create index if not exists idx_bank_q_pick
    on public.bank_questions (discipline_id, domain_id, difficulty, cognitive_level);
create index if not exists idx_bank_q_type
    on public.bank_questions (question_type);

create table if not exists public.bank_choices (
    id bigint generated by default as identity primary key,
    question_id bigint not null references public.bank_questions(id) on delete cascade,
    letter text not null check (letter in ('A', 'B', 'C', 'D', 'E')),
    choice_text text not null,
    image_path text,
    is_correct smallint not null check (is_correct in (0, 1)),
    unique (question_id, letter)
);

create table if not exists public.bank_accepted_answers (
    id bigint generated by default as identity primary key,
    question_id bigint not null references public.bank_questions(id) on delete cascade,
    answer_text text not null,
    answer_norm text not null,
    unique (question_id, answer_norm)
);
create index if not exists idx_bank_ans_q
    on public.bank_accepted_answers (question_id);

alter table public.bank_disciplines enable row level security;
alter table public.bank_domains enable row level security;
alter table public.bank_questions enable row level security;
alter table public.bank_choices enable row level security;
alter table public.bank_accepted_answers enable row level security;

revoke all on table public.bank_disciplines, public.bank_domains,
    public.bank_questions, public.bank_choices, public.bank_accepted_answers
    from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
