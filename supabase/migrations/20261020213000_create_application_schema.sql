create table if not exists public.users (
    id bigint generated by default as identity primary key,
    username text not null,
    email text not null,
    password_hash text not null,
    role text not null check (role in ('STUDENT', 'EXAMINER', 'ADMIN')),
    name text not null default '',
    discipline text not null default '',
    professional_title text not null default '',
    license_number text not null default '',
    examiner_status text not null default 'approved'
        check (examiner_status in ('pending', 'approved', 'rejected')),
    examiner_reviewed_at text,
    examiner_reviewed_by bigint references public.users(id)
        deferrable initially deferred,
    invalid_attempts integer not null default 0,
    is_locked smallint not null default 0 check (is_locked in (0, 1)),
    created_at text not null default current_timestamp
);

create unique index if not exists users_username_ci
    on public.users (lower(username));
create unique index if not exists users_email_ci
    on public.users (lower(email));
create unique index if not exists unique_examiner_license
    on public.users (lower(license_number)) where license_number <> '';

create table if not exists public.sessions (
    token_hash text primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    csrf_token text not null,
    expires_at bigint not null
);

create table if not exists public.password_reset_requests (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    new_password_hash text not null,
    status text not null default 'pending'
        check (status in ('pending', 'approved', 'rejected')),
    requested_at text not null default current_timestamp,
    reviewed_at text,
    reviewed_by bigint references public.users(id)
);
create unique index if not exists one_pending_reset
    on public.password_reset_requests(user_id) where status = 'pending';

create table if not exists public.questions (
    id text primary key,
    q text not null,
    opts_json text not null,
    ans integer not null check (ans between 0 and 3),
    domain text not null,
    cognitive text not null,
    difficulty text not null,
    explanation text not null default ''
);

create table if not exists public.imported_question_overrides (
    question_id text primary key,
    payload_json text not null default '{}',
    is_deleted smallint not null default 0 check (is_deleted in (0, 1))
);

create table if not exists public.question_change_requests (
    id bigint generated by default as identity primary key,
    proposer_id bigint not null references public.users(id) on delete cascade,
    action text not null check (action in ('ADD', 'EDIT', 'DELETE')),
    target_question_id text,
    payload_json text not null,
    status text not null default 'pending'
        check (status in ('pending', 'approved', 'rejected')),
    submitted_at text not null default current_timestamp,
    reviewed_at text,
    reviewed_by bigint references public.users(id),
    rejection_reason text not null default ''
);

create table if not exists public.exam_history (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    title text not null,
    score_pct integer not null,
    total_items integer not null,
    correct_items integer not null,
    domains_json text not null,
    report_json text,
    created_at text not null default current_timestamp
);

create table if not exists public.licensure_attempts (
    id text primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    question_ids_json text not null,
    planned_json text,
    started_at bigint not null,
    submitted_at bigint,
    mode text not null default 'licensure',
    title text not null default 'Mock Licensure Exam',
    selected_domains_json text,
    time_seconds integer not null default 3600,
    expires_at bigint,
    answers_json text not null default '{}',
    result_id bigint references public.exam_history(id),
    abandoned_at bigint
);

create table if not exists public.requests (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    title text not null,
    domain text not null,
    difficulty text not null,
    notes text not null default '',
    status text not null default 'Pending',
    admin_comment text not null default '',
    created_at text not null default current_timestamp
);

alter table public.users enable row level security;
alter table public.sessions enable row level security;
alter table public.password_reset_requests enable row level security;
alter table public.questions enable row level security;
alter table public.imported_question_overrides enable row level security;
alter table public.question_change_requests enable row level security;
alter table public.exam_history enable row level security;
alter table public.licensure_attempts enable row level security;
alter table public.requests enable row level security;

revoke all on all tables in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
